"""Generates docs/WEATHER_EFFECTS.md from luarules/configs/weather_defs.lua.

weather_defs.lua is the single source of truth, so rerun this after changing it:
    pip install lupa
    python tools/gen_effects_table.py
"""
import os

from lupa import LuaRuntime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFS = os.path.join(ROOT, "mod", "BAR-Weather.sdd", "luarules", "configs", "weather_defs.lua")
OUT = os.path.join(ROOT, "docs", "WEATHER_EFFECTS.md")


def lua_list(t):
    return [t[i] for i in range(1, len(t) + 1)]


def fmt_mod(value):
    if value is None:
        return "–"
    if value is True:
        return "✔"
    return f"{value:g}×"


def generate():
    lua = LuaRuntime(unpack_returned_tuples=True)
    with open(DEFS, encoding="utf-8") as f:
        defs = lua.execute(f.read())

    types = lua_list(defs.TypeOrder)
    conds = types + ["night"]
    label = {t: defs.Types[t].label for t in types}
    label["night"] = defs.Night.label

    out = [
        "# Weather and status effects",
        "",
        "<!-- Generated by tools/gen_effects_table.py from weather_defs.lua. Do not edit by hand. -->",
        "",
        "Values are at full intensity. During a transition every modifier blends in: "
        "`effective = 1 + (mod - 1) × intensity`, and the `weather_effect_scale` modoption is meant to scale them further. "
        "Night stacks on top of whatever the weather is.",
        "",
        "> **Status:** the weather itself cycles in game, but no effect gadgets exist yet (Phase 4+). "
        "These are the planned values; the HUD only lists a modifier once its system is live.",
        "",
        "## Who wins",
        "",
        "| Condition | Favors | Hurts |",
        "|---|---|---|",
    ]
    for c in conds:
        src = defs.Night if c == "night" else defs.Types[c]
        out.append(f"| **{label[c]}** | {src.favors} | {src.hurts} |")

    out += [
        "",
        "## Modifiers",
        "",
        "`×` values are multipliers; ✔ marks an on/off mechanic; – means unaffected.",
        "",
        "| Effect | System | " + " | ".join(label[c] for c in conds) + " |",
        "|---|---|" + "---|" * len(conds),
    ]
    for key in lua_list(defs.ModifierOrder):
        info = defs.ModifierInfo[key]
        cells = [fmt_mod(defs.Modifiers[c][key]) for c in conds]
        out.append(f"| {info.label} | {info.system} | " + " | ".join(cells) + " |")

    out += [
        "",
        "## Atmosphere",
        "",
        "| Weather | Precipitation | Cloud | Fog | Wind (min–max) |",
        "|---|---|---|---|---|",
    ]
    for t in types:
        w = defs.Types[t]
        out.append(f"| {label[t]} | {w.precip:g} | {w.cloud:g} | {w.fog:g} | {w.windMin:g}–{w.windMax:g} |")

    out += [
        "",
        "## Climates",
        "",
        "| Climate | Allowed weather |",
        "|---|---|",
    ]
    for name in ("temperate", "arid", "arctic", "marsh"):
        allowed = [label[t] for t in types if defs.Climates[name].allowed[t]]
        out.append(f"| {name} | {', '.join(allowed)} |")

    return "\n".join(out) + "\n"


if __name__ == "__main__":
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(generate())
    print("wrote", os.path.relpath(OUT, ROOT))
